const DICT: Record<Locale, Record<MsgKey, string>> = { en, ar }
const STORE_KEY = 'pws.locale'

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORE_KEY)
    if (saved === 'en' || saved === 'ar') return saved
  } catch { /* ignore */ }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('ar') ? 'ar' : 'en'
}

export type Translate = (key: MsgKey, vars?: Record<string, string | number>) => string

interface I18nState { locale: Locale; dir: Dir; t: Translate; setLocale: (l: Locale) => void; toggle: () => void }
const Ctx = createContext<I18nState | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale)
  const dir: Dir = locale === 'ar' ? 'rtl' : 'ltr'

  useEffect(() => {
    const el = document.documentElement
    el.lang = locale
    el.dir = dir
    try { localStorage.setItem(STORE_KEY, locale) } catch { /* ignore */ }
  }, [locale, dir])

  const t = useCallback<Translate>(
    (key, vars) => {
      const raw = DICT[locale][key] ?? DICT.en[key] ?? key
      return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : raw
    },
    [locale],
  )

  const value = useMemo<I18nState>(
    () => ({ locale, dir, t, setLocale, toggle: () => setLocale((l) => (l === 'en' ? 'ar' : 'en')) }),
    [locale, dir, t],
  )
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n outside I18nProvider')
  return v
}

/** Locale-aware date formatting; Arabic keeps Latin digits so IDs and timestamps stay scannable. */
export function useFormatDate() {
  const { locale } = useI18n()
  return useCallback(
    (iso?: string | null) =>
      iso
        ? new Date(iso).toLocaleString(locale === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB', { dateStyle: 'medium', timeStyle: 'short' })
        : '—',
    [locale],
  )
}

const AUDIT_KEYS: Record<string, MsgKey> = {
  created: 'activity.created',
  updated: 'activity.updated',
  'config saved': 'activity.configSaved',
  'imported from api': 'activity.importedFromApi',
}

/** Translates a server-side audit action, falling back to the raw string for anything new. */
export function useAuditLabel() {
  const { t } = useI18n()
  return useCallback((action: string) => (AUDIT_KEYS[action] ? t(AUDIT_KEYS[action]) : action), [t])
}
